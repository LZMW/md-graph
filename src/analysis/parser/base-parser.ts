// =============================================================================
// DocumentParser 接口 + DocumentFormat 类型
// 定义所有文档解析器必须实现的接口契约
// =============================================================================
import type { ParsedDocument } from '../../types.js';

// ---------------------------------------------------------------------------
// 文档格式类型
// ---------------------------------------------------------------------------
export type DocumentFormat = 'md' | 'mdx';

// ---------------------------------------------------------------------------
// DocumentParser 接口
// 所有文档解析器必须实现此接口
// ---------------------------------------------------------------------------
export interface DocumentParser {
  /** 解析文档内容为结构化 DocNode 数组 */
  parse(content: string, filePath?: string): ParsedDocument;

  /** 支持的解析格式（如 'md', 'mdx'） */
  supportedFormat: DocumentFormat;

  /** 不适用的场景声明 */
  readonly unsuitableFor?: string[];
}
